def check_dependencies():
    """
    Function to check if required Python packages are installed.
    """
    print("\nStep 3: Check Dependencies")
    print("-" * 70)
    
    required_packages = [
        ('dotenv', 'python-dotenv'),
        ('yaml', 'PyYAML'),
        ('requests', 'requests')
    ]
    
    missing = []
    for import_name, package_name in required_packages:
        try:
            __import__(import_name)
        except ImportError:
            missing.append(package_name)
    
    if missing:
        print("ERROR: Missing required dependencies!")
        print("\nThe following packages need to be installed:")
        for pkg in missing:
            print(f"  - {pkg}")
        print("\nTo install all required packages:")
        print("  pip install -r requirements.txt")
        print("\nOr install manually:")
        print(f"  pip install {' '.join(missing)}")
        return False
    
    print("SUCCESS: All required dependencies are installed")
    return True

def test_connection():
    """
    Function to test Alpaca API connection using paper trading keys.
    """
    print("\nStep 4: Test Connection")
    print("-" * 70)
    
    try:
        # Add core to path for shared clients
        core_path = Path(__file__).parent.parent.parent / 'core'
        if not core_path.exists():
            print("ERROR: Missing 'core/' directory!")
            print(f"Expected location: {core_path}")
            print("\nThe shared code directory is required for this setup.")
            print("Please ensure the full repository is cloned.")
            return False
        
        sys.path.insert(0, str(core_path))
        
        from clients import AlpacaTrader
        from dotenv import load_dotenv
        
        load_dotenv()
        
        alpaca_key = os.getenv('ALPACA_API_KEY')
        alpaca_secret = os.getenv('ALPACA_SECRET_KEY')
        
        if not alpaca_key or not alpaca_secret:
            print("ERROR: API keys not found in .env")
            return False
        
        print("\nTesting Alpaca connection...")
        trader = AlpacaTrader(alpaca_key, alpaca_secret, paper=True)
        account = trader.get_account()
        
        print("SUCCESS: Connected to Alpaca (Paper Trading)")
        print(f"  Account Status: {account['status']}")
        print(f"  Buying Power: ${float(account['buying_power']):.2f}")
        
        return True
        
    except Exception as e:
        print(f"ERROR: Connection failed: {str(e)}")
        print("\nPlease check your API keys and try again.")
        return False

def run_simulation():
    """
    Function to run a test simulation with the configured settings.
    """
    print("\nStep 5: Run Test Simulation")
    print("-" * 70)
    print("\nRunning test simulation with your configuration...")
    print("(This won't execute any real trades)\n")
    
    try:
        import subprocess
        result = subprocess.run(
            [sys.executable, 'main.py', 'simulate'],
            capture_output=True,
            text=True
        )
        
        print(result.stdout)
        
        if result.returncode == 0:
            print("\nSimulation successful!")
            return True
        else:
            print(f"\nSimulation failed: {result.stderr}")
            return False
            
    except Exception as e:
        print(f"Failed to run simulation: {str(e)}")
        return False

