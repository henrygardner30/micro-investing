def check_existing_env():
    """
    Function to check if the .env file exists and has the required API keys.
    """
    env_path = Path('.env')
    if env_path.exists():
        with open(env_path, 'r') as f:
            content = f.read()
            if 'ALPACA_API_KEY' in content and 'your_alpaca' not in content:
                return True
    return False

def setup_env_file():
    """
    Function to guide user through creating .env file with API keys.
    """
    print("\nStep 1: API Keys Setup")
    print("-" * 70)
    
    if check_existing_env():
        print("Found existing .env file with API keys")
        use_existing = input("\nUse existing keys? (y/n): ").lower().strip()
        if use_existing == 'y':
            return True
    
    print("\nYou need Alpaca API keys to get started.")
    print("Get them here: https://app.alpaca.markets/paper/dashboard/overview")
    print()
    
    alpaca_key = input("Alpaca API Key: ").strip()
    alpaca_secret = input("Alpaca Secret Key: ").strip()
    
    if not alpaca_key or not alpaca_secret:
        print("\nBoth Alpaca keys are required!")
        return False
    
    # optional: the card caddie for rewards strategy
    print("\nOptional: The Card Caddie API key (only needed for credit card rewards strategy)")
    print("Get it here: https://www.thecardcaddie.com/profile")
    cardcaddie_key = input("The Card Caddie API Key (press Enter to skip): ").strip()
    
    # optional: email notifications
    print("\nOptional: Email notifications (for alerts)")
    smtp_user = input("Your Gmail address (press Enter to skip): ").strip()
    smtp_password = ""
    if smtp_user:
        smtp_password = input("Gmail App Password (press Enter to skip): ").strip()
    
    # write .env file
    env_content = dedent(f"""\
        # Micro-Investing Engine - Environment Variables
        # Generated by setup.py

        # Alpaca Trading (required)
        ALPACA_API_KEY={alpaca_key}
        ALPACA_SECRET_KEY={alpaca_secret}

        # The Card Caddie API (optional - for credit_card_rewards strategy)
        {f'THECARDCADDIE_API_KEY={cardcaddie_key}' if cardcaddie_key else '# THECARDCADDIE_API_KEY=your_key_here'}

        # Email Notifications (optional)
        {f'SMTP_USER={smtp_user}' if smtp_user else '# SMTP_USER=your@gmail.com'}
        {f'SMTP_PASSWORD={smtp_password}' if smtp_password else '# SMTP_PASSWORD=your_app_password'}
        """)
    
    with open('.env', 'w') as f:
        f.write(env_content)
    
    print("\nCreated .env file with your API keys")
    return True

def setup_config():
    """
    Function to guide user through configuring their investment strategies.
    Allows selecting multiple strategies at once.
    """
    print("\nStep 2: Choose Investment Strategies")
    print("-" * 70)
    print("\nYou can enable multiple strategies to run simultaneously!")
    print()
    print("Available Strategies:")
    print("  1. Scheduled Investment (Recommended - Easiest!)")
    print("     Invest a fixed amount at regular intervals")
    print("     No transaction data needed")
    print()
    print("  2. Round Up (Spare change from transactions)")
    print("     Requires transaction CSV file")
    print()
    print("  3. Credit Card Rewards (Advanced)")
    print("     Requires The Card Caddie API + transaction CSV")
    print()
    
    print("Select strategies to enable:")
    print("  - Enter numbers separated by commas (e.g., 1,2)")
    print("  - Or press Enter for default (Scheduled only)")
    
    choice = input("\nYour choice [1]: ").strip() or "1"
    
    # parse choices
    selected = []
    for c in choice.split(','):
        c = c.strip()
        if c in ['1', '2', '3']:
            selected.append(c)
    
    if not selected:
        selected = ['1']
    
    # remove duplicates and sort
    selected = sorted(list(set(selected)))
    
    print("\nSelected strategies:")
    strategy_info = []
    
    if '1' in selected:
        print("  [ENABLED] Scheduled Investment")
        print("    Default: $5 daily into VOO (60%) and QQQ (40%)")
        strategy_info.append({
            'name': 'Scheduled Investment',
            'requires_csv': False,
            'requires_api': False
        })
    
    if '2' in selected:
        print("  [ENABLED] Round Up")
        print("    Uses: data/transactions/transactions.csv")
        strategy_info.append({
            'name': 'Round Up',
            'requires_csv': True,
            'requires_api': False
        })
    
    if '3' in selected:
        print("  [ENABLED] Credit Card Rewards")
        print("    Requires: The Card Caddie API key + transaction CSV")
        strategy_info.append({
            'name': 'Credit Card Rewards',
            'requires_csv': True,
            'requires_api': True
        })
    
    # check requirements
    needs_csv = any(s['requires_csv'] for s in strategy_info)
    needs_api = any(s['requires_api'] for s in strategy_info)
    
    print()
    if needs_csv:
        print("Note: Transaction CSV strategies will use data/transactions/transactions.csv")
        print("      Example data is already provided for testing")
    
    if needs_api:
        cardcaddie_key = os.getenv('THECARDCADDIE_API_KEY')
        if not cardcaddie_key:
            print()
            print("WARNING: Credit Card Rewards strategy requires:")
            print("         1. The Card Caddie API key (add THECARDCADDIE_API_KEY to .env)")
            print("            Get it here: https://www.thecardcaddie.com/profile")
            print("         2. Your credit cards added to your account at:")
            print("            https://www.thecardcaddie.com")
            print("         3. Card names in CSV must match card names in your account")
    
    print()
    print("To customize strategies, amounts, or allocations:")
    print("  Edit config.yml after setup completes")
    
    # create config.yml with selected strategies
    _create_config_file(selected)
    
    return True

